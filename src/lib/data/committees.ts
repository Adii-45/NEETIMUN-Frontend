import type { LucideIcon } from "lucide-react";
import { Banknote, Eye, Gavel, Landmark, Scale } from "lucide-react";

export type Committee = {
  id: string;
  slug: string;
  tag: string;
  title: string;
  shortDescription: string;
  agenda: string | null;
  description: string[];
  portfolioTypes: string[];
  /**
   * Full portfolio roster for the registration form's PortfolioSelect.
   * Distinct from `portfolioTypes` (the short category labels shown as
   * badges on the public Committees page) - this can be much longer and is
   * never rendered there. Omitted entirely for committees that don't have a
   * dedicated roster (falls back to an empty list).
   */
  registrationPortfolioTypes?: string[];
  badges: string[];
  icon: LucideIcon;
  sidebarLines: string[];
  featured?: boolean;
  href: string;
};

/**
 * Resolve a committee by its URL slug. Returns `undefined` for missing or
 * unknown slugs so callers can fall back gracefully.
 */
export function getCommitteeBySlug(slug?: string | null): Committee | undefined {
  return slug ? committees.find((committee) => committee.slug === slug) : undefined;
}

